/**
 * Resolve crest URL by normalized ID or team name
 */
export function getTeamCrestUrl(teamIdOrName: string): string | undefined {
  if (!teamIdOrName) return undefined;
  const key = teamIdOrName.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  if (TEAM_CREST_MAP[key]) return TEAM_CREST_MAP[key];

  // Try partial match
  for (const [id, url] of Object.entries(TEAM_CREST_MAP)) {
    if (key.includes(id) || id.includes(key)) {
      return url;
    }
  }
  return undefined;
}
